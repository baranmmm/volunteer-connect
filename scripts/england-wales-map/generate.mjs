// Generates the dotted (halftone) map of England and Wales for the public events map:
//   node scripts/england-wales-map/generate.mjs <ne_50m_admin_0_map_units.geojson>
// writes src/components/public/events-map/england-wales-dots.ts. See README.md for the source data (Natural Earth,
// public domain). The projection must match `project()` in src/lib/events-story.ts.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const K = Math.cos((52.5 * Math.PI) / 180);
/** Same as project() in src/lib/events-story.ts: [x, y] in map units (100 per degree of latitude). */
const project = (lon, lat) => [(lon + 6) * K * 100, (56 - lat) * 100];

const source = process.argv[2];
if (!source) {
  console.error(
    "usage: node scripts/england-wales-map/generate.mjs <ne_50m_admin_0_map_units.geojson>",
  );
  process.exit(1);
}
const data = JSON.parse(readFileSync(source, "utf8"));
const units = data.features.filter((f) => ["ENG", "WLS"].includes(f.properties.SU_A3));
if (units.length !== 2) throw new Error("England and Wales not found in the file");

/** Every ring (outer and holes) as projected points. */
const rings = [];
for (const f of units) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys)
    for (const ring of poly) rings.push(ring.map(([lon, lat]) => project(lon, lat)));
}

function inside(x, y) {
  // Even-odd rule over every ring (holes and islands alike).
  let c = false;
  for (const ring of rings)
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i],
        [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
}
function coastDistance(x, y) {
  let best = Infinity;
  for (const ring of rings)
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[j],
        [x2, y2] = ring[i];
      const dx = x2 - x1,
        dy = y2 - y1;
      const t =
        dx || dy
          ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
          : 0;
      best = Math.min(best, Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy)));
    }
  return best;
}

let minX = Infinity,
  minY = Infinity,
  maxX = -Infinity,
  maxY = -Infinity;
for (const ring of rings)
  for (const [x, y] of ring) {
    minX = Math.min(minX, x);
    maxX = Math.max(maxX, x);
    minY = Math.min(minY, y);
    maxY = Math.max(maxY, y);
  }

// A hexagonal grid: every other row shifted by half a step. Dots near the coast are smaller (the halftone look).
const STEP = 8;
const sizes = [[], [], []];
for (let row = 0, y = minY + STEP / 2; y < maxY; row++, y += STEP * 0.866) {
  for (let x = minX + (row % 2 ? STEP / 2 : 0); x < maxX; x += STEP) {
    if (!inside(x, y)) continue;
    const d = coastDistance(x, y);
    sizes[d < STEP * 0.75 ? 0 : d < STEP * 2 ? 1 : 2].push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
  }
}

const round = (n) => Math.round(n * 10) / 10;
const out = `// GENERATED by scripts/england-wales-map/generate.mjs from Natural Earth (public domain). Do not edit by hand.
// The dots of England and Wales in map units (see project() in src/lib/events-story.ts), drawn as round-capped
// zero-length strokes: one path per dot size (coast, near the coast, inland).
export const EW_BOUNDS = { minX: ${round(minX)}, minY: ${round(minY)}, maxX: ${round(maxX)}, maxY: ${round(maxY)} };
export const EW_DOT_STEP = ${STEP};
export const EW_DOTS: readonly [string, string, string] = [
${sizes.map((s) => `  "${s.join("")}",`).join("\n")}
];
`;
const target = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../../src/components/public/events-map/england-wales-dots.ts",
);
writeFileSync(target, out);
console.log(
  `${sizes.map((s) => s.length).join(" + ")} dots → ${path.relative(process.cwd(), target)} (${out.length} bytes)`,
);
