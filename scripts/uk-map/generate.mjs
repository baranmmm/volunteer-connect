// Generates the dotted (halftone) map of the United Kingdom (England, Wales, Scotland, Northern Ireland) for the public
// events map:
//   node scripts/uk-map/generate.mjs <ne_50m_admin_0_map_units.geojson>
// writes public/maps/uk-dots.svg (the dots, a static asset) and src/components/public/events-map/uk-dots.ts
// (its geometry only). See README.md for the source data (Natural Earth,
// public domain). The projection must match `project()` in src/lib/events-story.ts.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const K = Math.cos((54.5 * Math.PI) / 180);
/** Same as project() in src/lib/events-story.ts: [x, y] in map units (100 per degree of latitude). */
const project = (lon, lat) => [(lon + 9) * K * 100, (61 - lat) * 100];

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/uk-map/generate.mjs <ne_50m_admin_0_map_units.geojson>");
  process.exit(1);
}
const data = JSON.parse(readFileSync(source, "utf8"));
const units = data.features.filter((f) =>
  ["ENG", "WLS", "SCT", "NIR"].includes(f.properties.SU_A3),
);
if (units.length !== 4) throw new Error("The four UK nations were not found in the file");

/** Every ring (outer and holes) as projected points. */
const rings = [];
for (const f of units) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys)
    for (const ring of poly) rings.push(ring.map(([lon, lat]) => project(lon, lat)));
}

function inside(x, y) {
  // Even-odd rule over every ring (holes and islands alike).
  let c = false;
  for (const ring of rings)
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i],
        [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
}
function coastDistance(x, y) {
  let best = Infinity;
  for (const ring of rings)
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[j],
        [x2, y2] = ring[i];
      const dx = x2 - x1,
        dy = y2 - y1;
      const t =
        dx || dy
          ? Math.max(0, Math.min(1, ((x - x1) * dx + (y - y1) * dy) / (dx * dx + dy * dy)))
          : 0;
      best = Math.min(best, Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy)));
    }
  return best;
}

let minX = Infinity,
  minY = Infinity,
  maxX = -Infinity,
  maxY = -Infinity;
for (const ring of rings)
  for (const [x, y] of ring) {
    minX = Math.min(minX, x);
    maxX = Math.max(maxX, x);
    minY = Math.min(minY, y);
    maxY = Math.max(maxY, y);
  }

// A hexagonal grid: every other row shifted by half a step. Dots near the coast are smaller (the halftone look).
const STEP = 8;
const sizes = [[], [], []];
for (let row = 0, y = minY + STEP / 2; y < maxY; row++, y += STEP * 0.866) {
  for (let x = minX + (row % 2 ? STEP / 2 : 0); x < maxX; x += STEP) {
    if (!inside(x, y)) continue;
    const d = coastDistance(x, y);
    sizes[d < STEP * 0.45 ? 0 : d < STEP * 1.5 ? 1 : 2].push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
  }
}

const round = (n) => Math.round(n * 10) / 10;
// The SVG box: the land bounds plus one grid step, so the dots at the edge are never cut.
const box = {
  x: round(minX - STEP),
  y: round(minY - STEP),
  w: round(maxX - minX + 2 * STEP),
  h: round(maxY - minY + 2 * STEP),
};
const WIDTHS = [0.42, 0.52, 0.6].map((f) => round(f * STEP * 100) / 100);
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box.x} ${box.y} ${box.w} ${box.h}" width="${Math.round(box.w)}" height="${Math.round(box.h)}"><!-- United Kingdom, Natural Earth (public domain); generated by scripts/uk-map/generate.mjs --><g fill="none" stroke="#c3d0da" stroke-linecap="round">${sizes.map((s, i) => `<path stroke-width="${WIDTHS[i]}" d="${s.join("")}"/>`).join("")}</g></svg>\n`;
const ts = `// GENERATED by scripts/uk-map/generate.mjs from Natural Earth (public domain). Do not edit by hand.
// The land dots themselves are the static asset ${"/"}maps/uk-dots.svg (kept out of the JS module graph);
// this file holds only its geometry in map units (see project() in src/lib/events-story.ts).
/** The bounds of the land. */
export const UK_BOUNDS = { minX: ${round(minX)}, minY: ${round(minY)}, maxX: ${round(maxX)}, maxY: ${round(maxY)} };
/** The SVG's viewBox (the land plus one grid step). */
export const UK_SVG_BOX = { x: ${box.x}, y: ${box.y}, w: ${box.w}, h: ${box.h} };
export const UK_SVG_URL = "/maps/uk-dots.svg";
export const UK_DOT_COUNT = ${sizes.reduce((n, s) => n + s.length, 0)};
`;
const here = path.dirname(fileURLToPath(import.meta.url));
const tsTarget = path.resolve(here, "../../src/components/public/events-map/uk-dots.ts");
const svgTarget = path.resolve(here, "../../public/maps/uk-dots.svg");
mkdirSync(path.dirname(svgTarget), { recursive: true });
writeFileSync(tsTarget, ts);
writeFileSync(svgTarget, svg);
console.log(
  `${sizes.map((s) => s.length).join(" + ")} dots → ${path.relative(process.cwd(), svgTarget)} (${svg.length} bytes) and ${path.relative(process.cwd(), tsTarget)}`,
);
