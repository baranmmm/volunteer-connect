/** Web Mercator (unit sphere): x from the longitude, y downwards like SVG. */
export function project(lng: number, lat: number): [number, number] {
  const x = (lng * Math.PI) / 180;
  const y = -Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [x, y];
}

const SCALE = 1000;
const toPath = (ring: [number, number][]) =>
  ring
    .map(([lng, lat], i) => {
      const [x, y] = project(lng, lat);
      return `${i ? "L" : "M"}${(x * SCALE).toFixed(1)} ${(y * SCALE).toFixed(1)}`;
    })
    .join("") + "Z";

export const OUTLINE_PATHS = [toPath(GREAT_BRITAIN), toPath(IRELAND)];

/** A point in the SVG's coordinates. */
export function svgPoint(lat: number, lng: number): [number, number] {
  const [x, y] = project(lng, lat);
  return [x * SCALE, y * SCALE];
}

